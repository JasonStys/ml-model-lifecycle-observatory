/**
 * File: generate-code-index.mjs
 * Purpose: Generate exact authored-source declaration locations for maintainers and reviewers.
 * Symbols and line locations: this script generates docs/code-index.md, including itself.
 * Important variables: patterns and supportedExtensions define the extraction surface.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(repositoryRoot, "docs", "code-index.md");
const supportedExtensions = new Set([".py", ".mjs", ".sh", ".sql"]);
const excludedDirectories = new Set([
  ".artifacts",
  ".git",
  ".mypy_cache",
  ".pip-audit-cache",
  ".pytest_cache",
  ".ruff_cache",
  ".test-runtime",
  ".venv",
  "htmlcov",
]);
const patterns = [
  /^\s*(?:async\s+)?def\s+([A-Za-z_][\w]*)\s*\(/,
  /^\s*class\s+([A-Za-z_][\w]*)\b/,
  /\b(?:function|class)\s+([A-Za-z_$][\w$]*)/,
  /\b(?:const|let)\s+([A-Za-z_$][\w$]*)\b/,
  /^\s*CREATE\s+(?:OR\s+REPLACE\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_][\w]*)/i,
  /^\s*([A-Z][A-Z0-9_]+)\s*=/,
];

/** Recursively return authored source files while excluding generated and dependency trees. */
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return excludedDirectories.has(entry.name) ? [] : walk(path);
    return supportedExtensions.has(extname(path)) ? [path] : [];
  });
}

/** Extract the first named declaration matched on each physical source line. */
function extract(path) {
  return readFileSync(path, "utf8")
    .split(/\r?\n/)
    .flatMap((line, index) => {
      for (const pattern of patterns) {
        const match = line.match(pattern);
        if (match) return [{ line: index + 1, name: match[1] }];
      }
      return [];
    });
}

/** Render deterministic Markdown suitable for byte-for-byte freshness checks. */
function render() {
  const lines = [
    "# Code index",
    "",
    "Generated by `scripts/generate-code-index.mjs`. Source headers point here for exact",
    "declaration locations. Regenerate after source edits.",
    "",
  ];
  for (const path of walk(repositoryRoot).sort()) {
    const declarations = extract(path);
    if (declarations.length === 0) continue;
    const repositoryPath = relative(repositoryRoot, path).replaceAll("\\", "/");
    lines.push(`## \`${repositoryPath}\``, "");
    for (const declaration of declarations) {
      lines.push(`- Line ${declaration.line}: \`${declaration.name}\``);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Write the generated index or verify that the committed copy is current. */
function main() {
  const generated = render();
  if (process.argv.includes("--check")) {
    if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== generated) {
      console.error("docs/code-index.md is stale; run node scripts/generate-code-index.mjs");
      process.exitCode = 1;
      return;
    }
    console.log("Code index is current.");
    return;
  }
  writeFileSync(outputPath, generated, "utf8");
  console.log("Generated docs/code-index.md.");
}

main();
